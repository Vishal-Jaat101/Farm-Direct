// Helper functions
export function getOrderById(id) {
  return orders.find(o => o.id === id) || null;
}

export function getOrdersByBuyer(buyerId) {
  return orders.filter(o => o.buyerId === buyerId);
}

export function getOrdersByFarmer(farmerId) {
  return orders.filter(o => o.items.some(item => item.farmerId === farmerId));
}

export function getPendingOrders() {
  return orders.filter(o => o.status === ORDER_STATES.REQUESTED);
}

export function getActiveOrders() {
  return orders.filter(o =>
    [ORDER_STATES.CONFIRMED, ORDER_STATES.ESCROW_HELD, ORDER_STATES.PICKED_UP, ORDER_STATES.IN_TRANSIT].includes(o.status)
  );
}

export function getCompletedOrders() {
  return orders.filter(o =>
    [ORDER_STATES.DELIVERED, ORDER_STATES.PAYMENT_RELEASED, ORDER_STATES.CLOSED].includes(o.status)
  );
}
