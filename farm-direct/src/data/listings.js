// Helper functions
export function getListingById(id) {
  return listings.find(l => l.id === id) || null;
}

export function getListingsByFarmer(farmerId) {
  return listings.filter(l => l.farmerId === farmerId);
}

export function getActiveListings() {
  return listings.filter(l => l.status === 'active');
}

export function searchListings({ crop, grade, maxPrice, maxDistance, organic, sort }) {
  let results = listings.filter(l => l.status === 'active');

  if (crop) results = results.filter(l => l.crop.toLowerCase().includes(crop.toLowerCase()));
  if (grade) results = results.filter(l => l.grade === grade);
  if (maxPrice) results = results.filter(l => l.price <= maxPrice);
  if (organic !== undefined) results = results.filter(l => l.organic === organic);

  if (sort === 'price-low') results.sort((a, b) => a.price - b.price);
  if (sort === 'price-high') results.sort((a, b) => b.price - a.price);
  if (sort === 'rating') results.sort((a, b) => b.grade.localeCompare(a.grade));
  if (sort === 'freshness') results.sort((a, b) => new Date(b.harvestDate) - new Date(a.harvestDate));

  return results;
}
